const TIME_FLAVORS: ReadonlyArray<{
  from: number;
  to: number;
  titles: readonly string[];
}> = [
  { from: 6, to: 11, titles: ["Утренний старт", "Кофе и поезд"] },
  { from: 11, to: 17, titles: ["Дневной рандеву", "Лёгкий маршрут"] },
  { from: 17, to: 23, titles: ["Вечерний побег", "Ночной экспресс"] },
];

export function randomTripTitle(now: Date): string {
  const pool = [...TITLES_BY_MONTH[now.getMonth()]!];
  const hour = now.getHours();
  const flavor = TIME_FLAVORS.find(({ from, to }) => hour >= from && hour < to);
  if (flavor) pool.push(...flavor.titles);
  const index = Math.floor(Math.random() * pool.length);
  return pool[index]!;
}
