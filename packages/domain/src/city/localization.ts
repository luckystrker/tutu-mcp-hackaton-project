let englishById: ReadonlyMap<string, string> = new Map();

export function configureCityLocalization(cities: readonly City[]): void {
  const catalogIds = new Set(cities.map((city) => city.id));
  const extra = Object.keys(ENGLISH_CITY_NAMES).filter(
    (id) => !catalogIds.has(id),
  );
  const missing = cities.filter((city) => !ENGLISH_CITY_NAMES[city.id]);
  if (extra.length > 0 || missing.length > 0)
    throw new Error(
      `Localized city names do not match the catalog: missing=${missing
        .map((city) => city.id)
        .join(", ")}, extra=${extra.join(", ")}`,
    );
  englishById = new Map(Object.entries(ENGLISH_CITY_NAMES));
}

export function cityDisplayName(
  city: Pick<PublicCity, "id" | "name">,
  locale: SupportedLocale,
): string {
  return locale === "en" ? (englishById.get(city.id) ?? city.name) : city.name;
}

export function localizeCity(city: City, locale: SupportedLocale): City {
  const name = cityDisplayName(city, locale);
  return name === city.name ? city : { ...city, name };
}

export function localizePublicCity(
  city: PublicCity,
  locale: SupportedLocale,
): PublicCity {
  const name = cityDisplayName(city, locale);
  return name === city.name ? city : { ...city, name };
}
